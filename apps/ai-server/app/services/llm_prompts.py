def _format_item_bank() -> str:
    blocks = []
    for scale_type, items in SCALE_ITEM_BANK.items():
        lines = "\n".join(f"  {i}. {text}" for i, text in enumerate(items, start=1))
        blocks.append(f"{_SCALE_ITEM_BANK_HEADERS[scale_type]}\n{lines}")
    return "\n\n".join(blocks)


